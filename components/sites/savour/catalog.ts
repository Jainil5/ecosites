import type { Course, MenuItemRow, PlaceRow, PriceBand, ReviewRow } from './types';

export type PlaceSeed = Omit<PlaceRow, 'id'>;
export type DishSeed = Omit<MenuItemRow, 'id' | 'place_id'>;
export type ReviewSeed = Omit<ReviewRow, 'id' | 'place_id'>;

export interface VenueSeed {
  place: PlaceSeed;
  dishes: DishSeed[];
  reviews: ReviewSeed[];
}

/** Inclusive low, exclusive high per band: sanity-checks that ₹₹₹₹ means fine dining. */
export const BAND_PRICE_CEILING: Record<PriceBand, [number, number]> = {
  '₹': [0, 400],
  '₹₹': [100, 800],
  '₹₹₹': [300, 1800],
  '₹₹₹₹': [600, 6000],
};

const COURSES: Course[] = ['aperitif', 'starter', 'main', 'breads', 'dessert', 'beverage'];
const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

export function validateCatalog(catalog: VenueSeed[]): string[] {
  const errs: string[] = [];
  if (catalog.length !== 12) errs.push(`expected 12 venues, got ${catalog.length}`);
  const slugs = new Set<string>();
  for (const v of catalog) {
    const p = v.place;
    const label = p.slug || p.name || '<unnamed>';
    if (!SLUG_RE.test(p.slug)) errs.push(`${label}: slug "${p.slug}" is not kebab-case`);
    if (slugs.has(p.slug)) errs.push(`${label}: duplicate slug`);
    slugs.add(p.slug);
    if (!p.name.trim()) errs.push(`${label}: name is required`);
    if (p.city !== 'Pune') errs.push(`${label}: city must be Pune, got "${p.city}"`);
    if (p.state !== 'Maharashtra') errs.push(`${label}: state must be Maharashtra`);
    if (p.rating !== null && (p.rating < 0 || p.rating > 5)) errs.push(`${label}: rating out of 0-5`);
    if (p.positive_reviews > p.num_reviews) errs.push(`${label}: positive_reviews exceeds num_reviews`);
    if (p.verified_at !== null && !DATE_RE.test(p.verified_at)) errs.push(`${label}: verified_at must be YYYY-MM-DD`);
    if (p.lat === null || p.lng === null) errs.push(`${label}: lat/lng required`);
    else if (p.lat < 18.3 || p.lat > 18.7 || p.lng < 73.6 || p.lng > 74.1)
      errs.push(`${label}: coords outside Pune bounding box`);
    if (!(p.price_band in BAND_PRICE_CEILING)) errs.push(`${label}: unknown price_band`);

    if (v.dishes.length < 8) errs.push(`${label}: needs at least 8 dishes`);
    if (!v.dishes.some((d) => d.is_signature)) errs.push(`${label}: needs at least 1 signature dish`);
    if (v.reviews.length < 3) errs.push(`${label}: needs at least 3 reviews`);

    const names = new Set<string>();
    const [low, high] = BAND_PRICE_CEILING[p.price_band] ?? [0, Infinity];
    for (const d of v.dishes) {
      if (names.has(d.name)) errs.push(`${label}: duplicate dish "${d.name}"`);
      names.add(d.name);
      if (d.name.length > 80) errs.push(`${label}: dish name over 80 chars`);
      if (!COURSES.includes(d.course)) errs.push(`${label}: bad course "${d.course}" on "${d.name}"`);
      if (!(d.price > 0)) errs.push(`${label}: dish "${d.name}" needs a positive price`);
      if (d.price >= high) errs.push(`${label}: dish "${d.name}" price ${d.price} out of band ${p.price_band}`);
      if (d.price < low) errs.push(`${label}: dish "${d.name}" price ${d.price} below band ${p.price_band}`);
    }
    for (const r of v.reviews) {
      if (!r.author.trim()) errs.push(`${label}: review author required`);
      if (r.rating < 1 || r.rating > 5) errs.push(`${label}: review rating out of 1-5`);
      if (r.body.trim().length < 20) errs.push(`${label}: review body too short`);
      if (r.visited_on !== null && !DATE_RE.test(r.visited_on))
        errs.push(`${label}: review visited_on must be YYYY-MM-DD`);
    }
  }
  return errs;
}

