import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { CATALOG, validateCatalog, type VenueSeed } from '../components/sites/savour/catalog';

/** Stable uuid per input, so re-running the seed updates rows instead of duplicating them. */
export function gen(seed: string): string {
  const h = createHash('sha1')
    .update(`savour:${seed}`)
    .digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

export function q(v: string | number | null | undefined): string {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

function textArray(items: string[]): string {
  if (items.length === 0) return "'{}'::text[]";
  return `array[${items.map((i) => q(i)).join(', ')}]::text[]`;
}

const PLACE_COLS =
  'id, slug, name, city, state, area, address, lat, lng, cuisines, price_band, cost_for_two, rating, num_reviews, positive_reviews, phone, website, instagram, hours, image_url, data_source, verified_at';

export function buildSeedSql(catalog: VenueSeed[]): string {
  const errs = validateCatalog(catalog);
  if (errs.length) throw new Error(`catalogue invalid:\n${errs.join('\n')}`);

  const out: string[] = [
    '-- Savour seed. Generated by scripts/savour-seed.ts — do not edit by hand.',
    '-- Idempotent: re-running updates the same rows instead of duplicating them.',
    '',
  ];

  for (const v of catalog) {
    const pid = gen(v.place.slug);
    const p = v.place;
    out.push(
      `-- venue: ${p.name}`,
      `insert into public.places (${PLACE_COLS})`,
      'values',
      [
        `  (${q(pid)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.city)}, ${q(p.state)},`,
        `   ${q(p.area)}, ${q(p.address)}, ${p.lat ?? 'null'}, ${p.lng ?? 'null'},`,
        `   ${textArray(p.cuisines)}, ${q(p.price_band)}, ${p.cost_for_two ?? 'null'},`,
        `   ${p.rating ?? 'null'}, ${p.num_reviews}, ${p.positive_reviews},`,
        `   ${q(p.phone)}, ${q(p.website)}, ${q(p.instagram)},`,
        `   ${p.hours === null ? 'null' : `${q(JSON.stringify(p.hours))}::jsonb`}, ${q(p.image_url)},`,
        `   ${q(p.data_source)}, ${q(p.verified_at)})`,
      ].join('\n'),
      'on conflict (slug) do update set',
      '  name = excluded.name, area = excluded.area, address = excluded.address,',
      '  lat = excluded.lat, lng = excluded.lng, cuisines = excluded.cuisines,',
      '  price_band = excluded.price_band, cost_for_two = excluded.cost_for_two,',
      '  rating = excluded.rating, num_reviews = excluded.num_reviews,',
      '  positive_reviews = excluded.positive_reviews, phone = excluded.phone,',
      '  website = excluded.website, instagram = excluded.instagram, hours = excluded.hours,',
      '  image_url = excluded.image_url, data_source = excluded.data_source,',
      '  verified_at = excluded.verified_at;',
      '',
      'insert into public.menu_items (id, place_id, name, course, course_rank, description, price, is_veg, is_signature)',
      'values',
      v.dishes
        .map(
          (d) =>
            `  (${q(gen(`${p.slug}#dish#${d.name}`))}, ${q(pid)}, ${q(d.name)}, ${q(d.course)}, ${d.course_rank}, ` +
            `${q(d.description)}, ${d.price}, ${d.is_veg === null ? 'null' : d.is_veg ? 'true' : 'false'}, ${d.is_signature ? 'true' : 'false'})`,
        )
        .join(',\n'),
      'on conflict (place_id, name) do update set',
      '  course = excluded.course, course_rank = excluded.course_rank,',
      '  description = excluded.description, price = excluded.price,',
      '  is_veg = excluded.is_veg, is_signature = excluded.is_signature;',
      '',
      'insert into public.reviews (id, place_id, author, rating, body, visited_on, source)',
      'values',
      v.reviews
        .map(
          (r) =>
            `  (${q(gen(`${p.slug}#review#${r.author}#${r.body.slice(0, 24)}`))}, ${q(pid)}, ${q(r.author)}, ` +
            `${r.rating}, ${q(r.body)}, ${q(r.visited_on)}, ${q(r.source)})`,
        )
        .join(',\n'),
      'on conflict (id) do nothing;',
      '',
    );
  }
  return out.join('\n');
}

if (process.argv[1] && path.basename(process.argv[1]) === 'savour-seed.ts') {
  writeFileSync(path.join(process.cwd(), 'supabase', 'seed.sql'), buildSeedSql(CATALOG), 'utf8');
  console.log('wrote supabase/seed.sql');
}
